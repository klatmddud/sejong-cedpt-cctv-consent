CREATE TABLE consent (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 학기 파기 시 수업, 수강과 함께 삭제된다
    enrollment_id  BIGINT       NOT NULL REFERENCES enrollment (id) ON DELETE CASCADE,
    language       VARCHAR(2)   NOT NULL,
    -- 세종대 포털 인증으로 확인한 이름 (명부 이름이 아님)
    signer_name    VARCHAR(100) NOT NULL,
    signed_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT consent_enrollment_uk UNIQUE (enrollment_id)
);

-- 목록 조회 때 큰 바이트를 읽지 않도록 분리
CREATE TABLE consent_document (
    consent_id     BIGINT PRIMARY KEY REFERENCES consent (id) ON DELETE CASCADE,
    signature_png  BYTEA NOT NULL,
    pdf            BYTEA NOT NULL
);
