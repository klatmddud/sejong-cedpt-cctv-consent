CREATE TABLE semester (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year        INT         NOT NULL,
    term        VARCHAR(10) NOT NULL,
    ends_on     DATE        NOT NULL,
    -- 동의서 일괄 파기일: 학기 종료일 + 1년
    purge_on    DATE        NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT semester_year_term_uk UNIQUE (year, term)
);

CREATE TABLE course (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id  BIGINT       NOT NULL REFERENCES semester (id) ON DELETE CASCADE,
    -- 학수번호-분반, 예: 000304-001
    code         VARCHAR(20)  NOT NULL,
    name         VARCHAR(200) NOT NULL,
    professor    VARCHAR(100),
    schedule     VARCHAR(100),
    room         VARCHAR(100) NOT NULL,
    CONSTRAINT course_semester_code_uk UNIQUE (semester_id, code)
);

CREATE TABLE enrollment (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id         BIGINT       NOT NULL REFERENCES course (id) ON DELETE CASCADE,
    student_id        VARCHAR(10)  NOT NULL,
    student_name      VARCHAR(100) NOT NULL,
    department        VARCHAR(100),
    grade             VARCHAR(10),
    -- 가장 최근에 올린 명부에 있는지 (수강 취소한 학생은 false, 이미 받은 동의는 유지)
    in_latest_roster  BOOLEAN      NOT NULL,
    CONSTRAINT enrollment_course_student_uk UNIQUE (course_id, student_id)
);

CREATE INDEX enrollment_student_id_idx ON enrollment (student_id);

CREATE TABLE roster_upload (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id       BIGINT       NOT NULL REFERENCES semester (id) ON DELETE CASCADE,
    file_name         VARCHAR(255) NOT NULL,
    uploaded_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    course_count      INT          NOT NULL,
    enrollment_count  INT          NOT NULL,
    added_count       INT          NOT NULL,
    removed_count     INT          NOT NULL
);
